// Generates src/lib/gallery-data.ts from the folders & images in public/gallery.
// Run via: npm run generate:gallery  (also wired into "build").
import { readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const IMAGE_EXTENSION = /\.(jpe?g|png|webp|avif|gif)$/i;

const prettifyLabel = (name) => name.trim().replace(/([a-z])([A-Z])/g, "$1 $2");

const slugify = (name) =>
  name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const base = path.join(root, "public", "gallery");
const outFile = path.join(root, "src", "lib", "gallery-data.ts");

const encodeStaticPath = (src) =>
  src
    .split("/")
    .map((segment) => encodeURIComponent(segment).replace(/%28/g, "(").replace(/%29/g, ")"))
    .join("/");

const entries = await readdir(base, { withFileTypes: true });

const categories = (
  await Promise.all(
    entries
      .filter((entry) => entry.isDirectory())
      .map(async (dir) => {
        const files = await readdir(path.join(base, dir.name));
        const images = files
          .filter((file) => IMAGE_EXTENSION.test(file))
          .sort((a, b) => a.localeCompare(b))
          .map((file) => encodeStaticPath(`/gallery/${dir.name}/${file}`));

        return { slug: slugify(dir.name), label: prettifyLabel(dir.name), images };
      }),
  )
).sort((a, b) => a.label.localeCompare(b.label));

const header = "// AUTO-GENERATED by scripts/generate-gallery-data.mjs — do not edit by hand.";
const typeDef =
  "export interface GalleryCategoryData {\n  slug: string;\n  label: string;\n  images: string[];\n}\n";
const body = `export const galleryCategories: GalleryCategoryData[] = ${JSON.stringify(
  categories,
  null,
  2,
)};\n`;

import { writeFile } from "node:fs/promises";
await writeFile(outFile, `${header}\n\n${typeDef}\n${body}`);
console.log(`Wrote ${outFile} (${categories.length} categories, ${categories.reduce((n, c) => n + c.images.length, 0)} images)`);